import {mkdir,readFile,writeFile,rename} from 'node:fs/promises';
import path from 'node:path';

export const REGISTRAR_CHROME_NAME='지오다노 등록기 전용';
export const REGISTRAR_CHROME_ORANGE=0xffff8a00|0;
async function readJson(file){try{return JSON.parse(await readFile(file,'utf8'));}catch(error){if(error.code==='ENOENT')return {};throw error;}}
async function writeJson(file,value){await mkdir(path.dirname(file),{recursive:true});await writeFile(file+'.registrar-tmp',JSON.stringify(value));await rename(file+'.registrar-tmp',file);}

// Call only before launching the dedicated profile, never while Chrome owns it.
export async function prepareRegistrarChromeAppearance(profile){
 if(path.basename(path.resolve(profile))!=='browser-profile-chrome-v2')throw Error('등록기 전용 크롬 프로필만 설정할 수 있습니다.');
 const file=path.join(profile,'Default','Preferences'),prefs=await readJson(file);
 prefs.profile={...prefs.profile,name:REGISTRAR_CHROME_NAME,using_default_name:false};
 prefs.autogenerated={...prefs.autogenerated,theme:{...prefs.autogenerated?.theme,color:REGISTRAR_CHROME_ORANGE}};
 prefs.extensions={...prefs.extensions,theme:{...prefs.extensions?.theme,id:'autogenerated_theme_id',pack:''}};
 prefs.browser={...prefs.browser,theme:{...prefs.browser?.theme,follows_system_colors:false,is_grayscale2:false}};
 await writeJson(file,prefs);
 const stateFile=path.join(profile,'Local State'),state=await readJson(stateFile);
 state.profile||={};state.profile.info_cache||={};
 state.profile.info_cache.Default={...state.profile.info_cache.Default,name:REGISTRAR_CHROME_NAME,is_using_default_name:false,profile_color_seed:REGISTRAR_CHROME_ORANGE};
 await writeJson(stateFile,state);
 return {name:REGISTRAR_CHROME_NAME,color:'#ff8a00'};
}
