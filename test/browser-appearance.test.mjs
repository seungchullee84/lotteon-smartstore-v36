import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {prepareRegistrarChromeAppearance,REGISTRAR_CHROME_ORANGE,REGISTRAR_CHROME_NAME} from '../browser-appearance.mjs';

test('전용 프로필 외의 일반 크롬은 변경하지 않는다',async()=>{
 await assert.rejects(prepareRegistrarChromeAppearance(path.join(os.tmpdir(),'ordinary-chrome')),/전용/);
});
test('주황색·프로필명만 바꾸고 기존 로그인·확장·기타 설정을 보존한다',async()=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'registrar-appearance-')),profile=path.join(dir,'browser-profile-chrome-v2');
 try{
  await mkdir(path.join(profile,'Default'),{recursive:true});
  const original={profile:{name:'이전',other:true},extensions:{settings:{existing:true}},signin:{allowed:true},browser:{other:'keep'}};
  await writeFile(path.join(profile,'Default','Preferences'),JSON.stringify(original));
  await writeFile(path.join(profile,'Local State'),JSON.stringify({profile:{info_cache:{Default:{user_name:'keep-existing'}}},os_crypt:{existing:'keep'}}));
  await prepareRegistrarChromeAppearance(profile);await prepareRegistrarChromeAppearance(profile);
  const prefs=JSON.parse(await readFile(path.join(profile,'Default','Preferences'),'utf8')),state=JSON.parse(await readFile(path.join(profile,'Local State'),'utf8'));
  assert.equal(prefs.profile.name,REGISTRAR_CHROME_NAME);assert.equal(prefs.autogenerated.theme.color,REGISTRAR_CHROME_ORANGE);assert.equal(prefs.extensions.theme.id,'autogenerated_theme_id');
  assert.deepEqual(prefs.extensions.settings,original.extensions.settings);assert.deepEqual(prefs.signin,original.signin);assert.equal(prefs.browser.other,'keep');
  assert.equal(state.profile.info_cache.Default.user_name,'keep-existing');assert.equal(state.os_crypt.existing,'keep');
 }finally{await rm(dir,{recursive:true,force:true});}
});
